using System.Collections.Immutable;
using System.Text;
using EntMap.Constants;
using EntMap.SourceGeneration.Models;

namespace EntMap.Builders;

public class GlobalMapperSourceBuilder(ImmutableArray<MappingPairData> pairs, string namespaceName)
{
    private readonly IndentedStringBuilder _sb = new();

    // 1. Добавьте метод верхнего уровня для вызова из генератора
    public string BuildWithInline(System.Collections.Immutable.ImmutableArray<InlineMappingCallData> inlineCalls)
    {
        _sb.Clear();

        BuildHeader()
            .BuildNamespaceStart()
            .BuildClassStart()
            .BuildInitMappersMethod()
            .BuildMappingMethods();

        // НОВЫЙ ВЫЗОВ: Генерируем жестко скомпилированные инлайн методы с атрибутами перехвата
        BuildInlineInterceptorMethods(inlineCalls);

        BuildClassEnd()
            .BuildNamespaceEnd();

        return _sb.ToString();
    }

    // 2. Добавьте генератор инлайн-методов
    private void BuildInlineInterceptorMethods(
        System.Collections.Immutable.ImmutableArray<InlineMappingCallData> inlineCalls)
    {
        foreach (var call in inlineCalls)
        {
            _sb.AppendLine("/// <summary> Расширенный метод маппинга игнорируя профиль, для этого нужно подключить функцию intercerptors в csproj <br/>");
            _sb.AppendLine("///<InterceptorsNamespaces>$(InterceptorsNamespaces);EntMap.Example;EntMap.Generators</InterceptorsNamespaces>");
            _sb.AppendLine("/// </summary>");
            // ИСПРАВЛЕНИЕ ДЛЯ .NET 10: Используем новый стабильный конструктор атрибута с версией и хэш-данными
            _sb.AppendLine(
                $"        [System.Runtime.CompilerServices.InterceptsLocation({call.InterceptorVersion}, \"{call.InterceptorData}\")]");
            _sb.AppendLine(
                $"        public static {call.TargetType} {call.UniqueMethodName}({call.SourceType} data, System.Action<{namespaceName}.{GlobalMapperConstants.ClassName}.InlineConfig<{call.SourceType}, {call.TargetType}>> _ignoredConfigDelegate)");
            _sb.AppendLine("        {");
            _sb.IncrementIndent();

            _sb.AppendLine("if (data == null) return null!;");
            _sb.AppendLine(
                $"var dto = ({call.TargetType})System.Runtime.CompilerServices.RuntimeHelpers.GetUninitializedObject(typeof({call.TargetType}));");
            _sb.AppendLine();

            foreach (var targetProp in call.TargetProperties)
            {
                if (call.CustomExpressions.TryGetValue(targetProp.Name, out var inlineExpression))
                {
                    _sb.AppendLine($"dto.{targetProp.Name} = {inlineExpression};");
                    continue;
                }

                var matchingSourcePropName = call.SourcePropertyNames
                    .FirstOrDefault(name => string.Equals(name, targetProp.Name, StringComparison.OrdinalIgnoreCase));

                if (matchingSourcePropName == null)
                {
                    if (targetProp.IsRequired) _sb.AppendLine($"dto.{targetProp.Name} = default!;");
                    continue;
                }

                if (targetProp.IsSimple)
                {
                    _sb.AppendLine($"dto.{targetProp.Name} = ({targetProp.TypeDisplay})data.{matchingSourcePropName};");
                }
                else
                {
                    _sb.AppendLine(
                        $"dto.{targetProp.Name} = data.{matchingSourcePropName} != null ? Map<{targetProp.TypeDisplay}>(data.{matchingSourcePropName}) : default!;");
                }
            }

            _sb.AppendLine("return dto;");
            _sb.DecrementIndent();
            _sb.AppendLine("        }");
            _sb.AppendLine();
        }
    }

    public string Build()
    {
        _sb.Clear();
        
        BuildHeader()
            .BuildNamespaceStart()
            .BuildClassStart()
            .BuildInitMappersMethod()
            .BuildMappingMethods()
            .BuildClassEnd()
            .BuildNamespaceEnd();

        return _sb.ToString();
    }

    private GlobalMapperSourceBuilder BuildHeader()
    {
        _sb.AppendLine("// EntMapGenerate <auto-generated />");
        _sb.AppendLine("#nullable enable");
        _sb.AppendLine("using System.Linq;");
        _sb.AppendLine("using System.Collections.Generic;");
        _sb.AppendLine("using System.Runtime.CompilerServices;"); 
        _sb.AppendLine();
        _sb.AppendLine($"// Всего обнаружено уникальных пар для кодогенерации: {pairs.Length}");
        return this;
    }

    private GlobalMapperSourceBuilder BuildNamespaceStart()
    {
        _sb.AppendLine($"namespace {namespaceName}");
        _sb.AppendLine("{");
        _sb.IncrementIndent();
        return this;
    }

    private GlobalMapperSourceBuilder BuildClassStart()
    {
        _sb.AppendLine($"internal static partial class {GlobalMapperConstants.ClassName}");
        _sb.AppendLine("{");
        _sb.IncrementIndent();
        return this;
    }

    private GlobalMapperSourceBuilder BuildInitMappersMethod()
    {
        _sb.AppendLine("static partial void InitMappers()");
        _sb.AppendLine("{");
        _sb.IncrementIndent();

        foreach (var pair in pairs)
        {
            var methodName = GetSafeMethodName(pair);
            _sb.AppendLine($"_mappers[(typeof({pair.Source}), typeof({pair.Target}))] = new System.Func<object, {pair.Target}>(src => {methodName}(({pair.Source})src));");
        }

        _sb.DecrementIndent();
        _sb.AppendLine("}");
        _sb.AppendLine();
        return this;
    }

    private GlobalMapperSourceBuilder BuildMappingMethods()
    {
        foreach (var pair in pairs)
        {
            var methodName = GetSafeMethodName(pair);

            _sb.AppendLine($"private static {pair.Target} {methodName}({pair.Source} data)");
            _sb.AppendLine("{");
            _sb.IncrementIndent();
            
            _sb.AppendLine("if (data == null) return null!;");
            _sb.AppendLine("bool isRoot = EntMap.MappingContext.Cache.Count == 0;");
            _sb.AppendLine("try {");
            _sb.IncrementIndent();

            _sb.AppendLine($"if (EntMap.MappingContext.Cache.TryGetValue(data, out var cached)) return ({pair.Target})cached;");
            _sb.AppendLine($"var dto = ({pair.Target})System.Runtime.CompilerServices.RuntimeHelpers.GetUninitializedObject(typeof({pair.Target}));");
            _sb.AppendLine("EntMap.MappingContext.Cache[data] = dto;");
            _sb.AppendLine();

            BuildPropertyAssignments(pair);

            _sb.AppendLine("return dto;");
            _sb.DecrementIndent();
            _sb.AppendLine("} finally {");
            _sb.IncrementIndent();
            _sb.AppendLine("if (isRoot) EntMap.MappingContext.Clear();");
            _sb.DecrementIndent();
            _sb.AppendLine("}");

            _sb.DecrementIndent();
            _sb.AppendLine("}");
            _sb.AppendLine();
        }
        return this;
    }

    private void BuildPropertyAssignments(MappingPairData pair)
    {
        foreach (var targetProp in pair.TargetProperties)
        {
            if (targetProp.HasCustomExpression)
            {
                _sb.AppendLine($"dto.{targetProp.Name} = {targetProp.CustomExpressionText};");
                continue;
            }

            var matchingSourcePropName = pair.SourcePropertyNames
                .FirstOrDefault(name => string.Equals(name, targetProp.Name, StringComparison.OrdinalIgnoreCase));

            if (matchingSourcePropName == null)
            {
                if (targetProp.IsRequired)
                {
                    _sb.AppendLine($"dto.{targetProp.Name} = default!;");
                }
                continue;
            }

            if (targetProp.IsSimple)
            {
                _sb.AppendLine($"dto.{targetProp.Name} = ({targetProp.TypeDisplay})data.{matchingSourcePropName};");
            }
            else if (targetProp.IsEnumerable)
            {
                // Используем коллекционные выражения из C# 12 [.. spread]
                _sb.AppendLine($"dto.{targetProp.Name} = data.{matchingSourcePropName} != null ? [.. data.{matchingSourcePropName}.Select(x => {namespaceName}.{GlobalMapperConstants.ClassName}.Map<{targetProp.ItemTypeDisplay}>(x))] : new();");
            }
            else
            {
                _sb.AppendLine($"dto.{targetProp.Name} = data.{matchingSourcePropName} != null ? {namespaceName}.{GlobalMapperConstants.ClassName}.Map<{targetProp.TypeDisplay}>(data.{matchingSourcePropName}) : default!;");
            }
        }
    }

    private GlobalMapperSourceBuilder BuildClassEnd()
    {
        _sb.DecrementIndent();
        _sb.AppendLine("}");
        return this;
    }

    private void BuildNamespaceEnd()
    {
        _sb.DecrementIndent();
        _sb.AppendLine("}");
    }

    // Централизованная очистка строк для безопасного имени метода
    private static string GetSafeMethodName(MappingPairData pair)
    {
        return $"Map{Clean(pair.Source)}To{Clean(pair.Target)}";

        string Clean(string typeName) => typeName
            .Replace(".", "")
            .Replace("<", "")
            .Replace(">", "")
            .Replace(" ", "")
            .Replace("[]", "Array")
            .Replace("global::", "")
            .Replace(":", "");
    }

    /// <summary>
    /// Вспомогательный класс для красивых и автоматических отступов в коде
    /// </summary>
    private sealed class IndentedStringBuilder
    {
        private readonly StringBuilder _innerSb = new();
        private int _indentLevel;
        private bool _isLineStart = true;

        public void IncrementIndent() => _indentLevel++;
        public void DecrementIndent() => _indentLevel = Math.Max(0, _indentLevel - 1);
        public void Clear() => _innerSb.Clear();

        public void AppendLine(string text = "")
        {
            if (string.IsNullOrEmpty(text))
            {
                _innerSb.AppendLine();
                _isLineStart = true;
                return;
            }

            if (_isLineStart)
            {
                _innerSb.Append(new string(' ', _indentLevel * 4));
            }

            _innerSb.AppendLine(text);
            _isLineStart = true;
        }

        public void Append(string text)
        {
            if (_isLineStart && !string.IsNullOrEmpty(text))
            {
                _innerSb.Append(new string(' ', _indentLevel * 4));
                _isLineStart = false;
            }
            _innerSb.Append(text);
        }

        public override string ToString() => _innerSb.ToString();
    }
}