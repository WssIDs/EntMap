using System.Collections.Immutable;
using System.Text;
using EntMap.Constants;
using EntMap.Extensions;
using EntMap.SourceGeneration.Structs;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace EntMap.Generators
{
    [Generator]
    public class AttributeSourceGenerator : IIncrementalGenerator
    {
        /// <summary>
        /// Генератор срабатывает, когда есть GenerateMapAttribute
        /// </summary>
        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var methodDeclarations = context.SyntaxProvider
                .CreateSyntaxProvider(
                    predicate: static (s, _) => IsCandidateMethod(s),
                    transform: static (ctx, _) => (MethodDeclarationSyntax)ctx.Node)
                .Where(static m => m != null);

            var methodInfos = methodDeclarations.Combine(context.CompilationProvider)
                .Select(static (tuple, _) => GetMappingMethodInfo(tuple.Left, tuple.Right))
                .Where(static info => info != null)
                .Select(static (x, _) => x!.Value);

            var allCollectedMethods = methodInfos.Collect();

            var groupedClasses = methodInfos.Combine(allCollectedMethods)
                .Select(static (tuple, _) => tuple.Left)
                .Collect()
                .SelectMany(static (methods, _) =>
                    methods.GroupBy(m => new { gClassName = m.ClassName, gNamespace = m.Namespace })
                        .Select(g => new ClassMappingData(g.Key.gClassName, g.Key.gNamespace, [.. g]))
                );

            context.RegisterSourceOutput(groupedClasses.Combine(allCollectedMethods).Combine(context.CompilationProvider),
                static (spc, megaTuple) =>
                {
                    var tuple = megaTuple.Left;
                    var compilation = megaTuple.Right;
                    
                    var classData = tuple.Left;
                    var allMethods = tuple.Right;
                    
                    var code = GenerateClassCode(classData.ClassName, classData.Namespace, classData.Methods, allMethods, compilation);
                    spc.AddSource($"{classData.ClassName}.g.cs", SourceText.From(code, Encoding.UTF8));
                });
        }

        /// <summary>
        /// Класс и метод должен быть partial иначе не получится создать новый сгенерированый класс
        /// </summary>
        /// <param name="node"></param>
        /// <returns></returns>
        private static bool IsCandidateMethod(SyntaxNode node)
        {
            return node is MethodDeclarationSyntax { AttributeLists.Count: > 0 } method &&
                   method.Modifiers.Any(m => m.ValueText == "partial") &&
                   method.Parent is ClassDeclarationSyntax classDecl &&
                   classDecl.Modifiers.Any(m => m.ValueText == "partial");
        }

        /// <summary>
        /// Получаем название метода
        /// </summary>
        /// <param name="methodSyntax"></param>
        /// <param name="compilation"></param>
        /// <returns></returns>
        private static MappingMethodInfo? GetMappingMethodInfo(MethodDeclarationSyntax methodSyntax, Compilation compilation)
        {
            var model = compilation.GetSemanticModel(methodSyntax.SyntaxTree);

            if (model.GetDeclaredSymbol(methodSyntax) is not IMethodSymbol methodSymbol || methodSymbol.Parameters.Length != 1) return null;

            var classSymbol = methodSymbol.ContainingType;

            if (classSymbol == null || methodSymbol.Parameters.FirstOrDefault()?.Type is not INamedTypeSymbol sourceType || methodSymbol.ReturnType is not INamedTypeSymbol targetType) return null;

            return new MappingMethodInfo(
                classSymbol.Name,
                classSymbol.ContainingNamespace.ToDisplayString(),
                methodSymbol.Name,
                sourceType,
                targetType,
                methodSymbol
            );
        }

        private static string GenerateClassCode(
            string className,
            string @namespace,
            ImmutableArray<MappingMethodInfo> classMethods,
            ImmutableArray<MappingMethodInfo> allMappingMethods,
            Compilation compilation)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated />");
            sb.AppendLine("#nullable enable");
            sb.AppendLine("using System.Linq;");
            sb.AppendLine("using System.Collections.Generic;");
            sb.AppendLine("using EntMap;");
            sb.AppendLine($"namespace {@namespace}");
            sb.AppendLine("{");
            sb.AppendLine($"    public static partial class {className}");
            sb.AppendLine("    {");

            foreach (var method in classMethods)
            {
                string sourceTypeName = method.SourceType.ToDisplayString();
                string targetTypeName = method.TargetType.ToDisplayString();

                bool isCollectionMapping =
                    (method.SourceType.AllInterfaces.Any(i => i.Name == "IEnumerable") ||
                     method.SourceType.Name == "IEnumerable") && method.SourceType.IsGenericType;

                if (isCollectionMapping)
                {
                    var sourceItemType = method.SourceType.TypeArguments.FirstOrDefault();
                    var targetItemType = method.TargetType.TypeArguments.FirstOrDefault();

                    var elementMappingMethod = allMappingMethods.FirstOrDefault(m =>
                    {
                        var pType = m.MethodSymbol.Parameters.FirstOrDefault()?.Type
                            .WithNullableAnnotation(NullableAnnotation.None);
                        var rType = m.MethodSymbol.ReturnType.WithNullableAnnotation(NullableAnnotation.None);
                        var sItem = sourceItemType?.WithNullableAnnotation(NullableAnnotation.None);
                        var tItem = targetItemType?.WithNullableAnnotation(NullableAnnotation.None);
                        return SymbolEqualityComparer.Default.Equals(pType, sItem) &&
                               SymbolEqualityComparer.Default.Equals(rType, tItem);
                    });

                    string mapCall = elementMappingMethod.MethodSymbol != null
                        ? $"{elementMappingMethod.Namespace}.{elementMappingMethod.ClassName}.{elementMappingMethod.MethodName}(x)"
                        : "default!";

                    sb.AppendLine(
                        $"        public static partial {targetTypeName} {method.MethodName}(this {sourceTypeName} data)");
                    sb.AppendLine("        {");
                    sb.AppendLine(
                        $"            if (data == null) return new List<{targetItemType?.ToDisplayString()}>();");
                    sb.AppendLine($"            return data.Select(x => {mapCall}).ToList();");
                    sb.AppendLine("        }");
                    continue;
                }

                // Извлекаем кастомные выражения ForMember для текущей пары типов из MappingProfile
                var customProfileRules =
                    FindCustomExpressionsForPair(compilation, method.SourceType, method.TargetType);

                // Если нужен дополнительный кастомный метод пост-маппинга в partial классе (например, MethodName_Custom)
                var customMethodName = $"{method.MethodName}_Custom";
                var hasCustomRulesMethod = method.MethodSymbol.ContainingType?
                                               .GetMembers()
                                               .OfType<IMethodSymbol>()
                                               .Any(m => m.Name == customMethodName &&
                                                         m.Parameters.Length == 1 &&
                                                         m.Parameters.FirstOrDefault()
                                                             ?.Type is INamedTypeSymbol pNamed &&
                                                         pNamed.IsGenericType &&
                                                         SymbolEqualityComparer.Default.Equals(
                                                             pNamed.TypeArguments.FirstOrDefault(),
                                                             method.SourceType) &&
                                                         SymbolEqualityComparer.Default.Equals(
                                                             pNamed.TypeArguments.LastOrDefault(), method.TargetType))
                                           ?? false;

                sb.AppendLine(
                    $"        public static partial {targetTypeName} {method.MethodName}(this {sourceTypeName} data)");
                sb.AppendLine("        {");
                sb.AppendLine("            if (data == null) return null!;");
                sb.AppendLine("            bool isRoot = EntMap.MappingContext.Cache.Count == 0;");
                sb.AppendLine("            try {");
                sb.AppendLine(
                    $"                if (EntMap.MappingContext.Cache.TryGetValue(data, out var cached)) return ({targetTypeName})cached;");
                sb.AppendLine("                ");
                sb.AppendLine(
                    $"                var dto = ({targetTypeName})System.Runtime.CompilerServices.RuntimeHelpers.GetUninitializedObject(typeof({targetTypeName}));");
                sb.AppendLine("                EntMap.MappingContext.Cache[data] = dto;");
                sb.AppendLine("                ");

                var sourceProps = method.SourceType.GetAllProperties();
                var targetProps = method.TargetType.GetAllProperties().Where(p => p.SetMethod != null).ToList();

                var assignmentLines = new List<string>();

                foreach (var targetProp in targetProps)
                {
                    // 1. Проверяем, есть ли для свойства кастомное выражение из Fluent API профиля
                    if (customProfileRules.TryGetValue(targetProp.Name, out var customExpression))
                    {
                        assignmentLines.Add($"                dto.{targetProp.Name} = {customExpression};");
                        continue;
                    }

                    var sourceProp = sourceProps.FirstOrDefault(p =>
                        string.Equals(p.Name, targetProp.Name, StringComparison.OrdinalIgnoreCase));
                    if (sourceProp == null)
                    {
                        if (targetProp.IsRequired)
                            assignmentLines.Add($"                dto.{targetProp.Name} = default!;");
                        continue;
                    }

                    var cleanTargetPropType = targetProp.Type.WithNullableAnnotation(NullableAnnotation.None);
                    var cleanSourcePropType = sourceProp.Type.WithNullableAnnotation(NullableAnnotation.None);
                    var isTargetSimple = cleanTargetPropType.IsSimple();
                    var isSourceSimple = cleanSourcePropType.IsSimple();
                    if (isTargetSimple && isSourceSimple)
                    {
                        assignmentLines.Add(
                            $"                dto.{targetProp.Name} = ({targetProp.Type.ToDisplayString()})data.{sourceProp.Name};");
                    }
                    else if (cleanTargetPropType is INamedTypeSymbol targetNamed &&
                             (targetNamed.AllInterfaces.Any(i => i.Name == "IEnumerable") ||
                              targetNamed.Name == "IEnumerable") &&
                             targetNamed.IsGenericType)
                    {
                        var targetItemType = targetNamed.TypeArguments.FirstOrDefault()
                            ?.WithNullableAnnotation(NullableAnnotation.None);
                        var sourceNamed = cleanSourcePropType as INamedTypeSymbol;
                        var sourceItemType = sourceNamed?.TypeArguments.FirstOrDefault()
                            ?.WithNullableAnnotation(NullableAnnotation.None);
                        var nestedMapping = allMappingMethods.FirstOrDefault(m =>
                        {
                            var pType = m.MethodSymbol.Parameters.FirstOrDefault()?.Type
                                .WithNullableAnnotation(NullableAnnotation.None);
                            var rType = m.MethodSymbol.ReturnType.WithNullableAnnotation(NullableAnnotation.None);
                            return SymbolEqualityComparer.Default.Equals(pType, sourceItemType) &&
                                   SymbolEqualityComparer.Default.Equals(rType, targetItemType);
                        });
                        if (nestedMapping.MethodSymbol != null)
                        {
                            var mapperClass = $"{nestedMapping.Namespace}.{nestedMapping.ClassName}";
                            var isInterface = targetNamed.TypeKind == TypeKind.Interface;
                            assignmentLines.Add(isInterface
                                ? $"                dto.{targetProp.Name} = data.{sourceProp.Name} != null ? data.{sourceProp.Name}.Select(x => {mapperClass}.{nestedMapping.MethodName}(x)).ToList() : new List<{targetItemType?.ToDisplayString()}>();"
                                : $"                dto.{targetProp.Name} = data.{sourceProp.Name} != null ? [.. data.{sourceProp.Name}.Select(x => {mapperClass}.{nestedMapping.MethodName}(x))] : new();");
                        }
                        else
                        {
                            var isInterface = targetNamed.TypeKind == TypeKind.Interface;
                            assignmentLines.Add(isInterface
                                ? $"                dto.{targetProp.Name} = new List<{targetItemType?.ToDisplayString()}>();"
                                : $"                dto.{targetProp.Name} = new();");
                        }
                    }
                    else if (targetProp.Type.IsReferenceType && sourceProp.Type.IsReferenceType &&
                             targetProp.Type.SpecialType != SpecialType.System_String)
                    {
                        var nestedMapping = allMappingMethods.FirstOrDefault(m =>
                        {
                            var pType = m.MethodSymbol.Parameters.FirstOrDefault()?.Type
                                .WithNullableAnnotation(NullableAnnotation.None);
                            var rType = m.MethodSymbol.ReturnType.WithNullableAnnotation(NullableAnnotation.None);
                            return SymbolEqualityComparer.Default.Equals(pType, cleanSourcePropType) &&
                                   SymbolEqualityComparer.Default.Equals(rType, cleanTargetPropType);
                        });
                        if (nestedMapping.MethodSymbol != null)
                        {
                            var mapperClass = $"{nestedMapping.Namespace}.{nestedMapping.ClassName}";
                            assignmentLines.Add(
                                $"                dto.{targetProp.Name} = data.{sourceProp.Name} != null ? {mapperClass}.{nestedMapping.MethodName}(data.{sourceProp.Name}) : default!;");
                        }
                        else if (targetProp.IsRequired)
                        {
                            assignmentLines.Add($"                dto.{targetProp.Name} = default!;");
                        }
                    }
                }

                sb.AppendLine(string.Join("\n", assignmentLines));
                sb.AppendLine();
                if (hasCustomRulesMethod)
                {
                    sb.AppendLine(
                        $"                var context = new MapContext<{sourceTypeName}, {targetTypeName}>(data, dto);");
                    sb.AppendLine($"                {customMethodName}(context);");
                }

                sb.AppendLine("                return dto;");
                sb.AppendLine("            } finally {");
                sb.AppendLine("                if (isRoot) EntMap.MappingContext.Clear();");
                sb.AppendLine("            }");
                sb.AppendLine("        }");
            }

            sb.AppendLine("    }");
            sb.AppendLine("}");
            return sb.ToString();
        }

        /// 
        /// Сканирует синтаксические деревья компиляции для поиска вызовов ForMember в MappingProfile для переданной пары типов.
        /// 
        private static Dictionary<string, string> FindCustomExpressionsForPair(Compilation compilation,
            INamedTypeSymbol source, INamedTypeSymbol target)
        {
            var customRules = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
            foreach (var tree in compilation.SyntaxTrees)
            {
                var root = tree.GetRoot();
                var semanticModel = compilation.GetSemanticModel(tree);
                var forMemberInvocations = root.DescendantNodes()
                    .OfType<InvocationExpressionSyntax>()
                    .Where(i => i.Expression is MemberAccessExpressionSyntax
                    {
                        Name.Identifier.ValueText: MapperProfileConstants.MemberMethodName
                    });
                foreach (var invocation in forMemberInvocations)
                {
                    var currentExpr = invocation.Expression;
                    InvocationExpressionSyntax? rootCreateMapInvocation = null;
                    while (currentExpr is MemberAccessExpressionSyntax maeChain)
                    {
                        if (maeChain.Expression is InvocationExpressionSyntax parentInv)
                        {
                            rootCreateMapInvocation = parentInv;
                            currentExpr = parentInv.Expression;
                        }
                        else
                        {
                            break;
                        }
                    }

                    if (rootCreateMapInvocation == null) continue;
                    var rootMethodName = string.Empty;
                    GenericNameSyntax? genericName = null;
                    switch (rootCreateMapInvocation.Expression)
                    {
                        case GenericNameSyntax gName:
                            rootMethodName = gName.Identifier.ValueText;
                            genericName = gName;
                            break;
                        case MemberAccessExpressionSyntax { Name: GenericNameSyntax maeGName }:
                            rootMethodName = maeGName.Identifier.ValueText;
                            genericName = maeGName;
                            break;
                    }

                    if (rootMethodName != MapperProfileConstants.CreateMapMethodName || genericName == null ||
                        genericName.TypeArgumentList.Arguments.Count != 2) continue;
                    var sourceSyntax = genericName.TypeArgumentList.Arguments[0];
                    var targetSyntax = genericName.TypeArgumentList.Arguments[1];
                    var evaluatedSource = semanticModel.GetTypeInfo(sourceSyntax).Type as INamedTypeSymbol;
                    var evaluatedTarget = semanticModel.GetTypeInfo(targetSyntax).Type as INamedTypeSymbol;
                    if (evaluatedSource == null || evaluatedTarget == null) continue;
                    if (semanticModel.GetSymbolInfo(rootCreateMapInvocation).Symbol is IMethodSymbol createMapSymbol)
                    {
                        var containingTypeDisplay = createMapSymbol.ContainingType?.ToDisplayString();
                        if (containingTypeDisplay == null || !containingTypeDisplay.StartsWith($"{GlobalMapperConstants.MainNamespace}."))
                            continue;
                    }

                    if (!SymbolEqualityComparer.Default.Equals(evaluatedSource, source) ||
                        !SymbolEqualityComparer.Default.Equals(evaluatedTarget, target)) continue;
                    if (invocation.ArgumentList.Arguments.Count == 2)
                    {
                        var destArg = invocation.ArgumentList.Arguments[0].Expression;
                        var mapFromArg = invocation.ArgumentList.Arguments[1].Expression;
                        string? targetPropertyName = null;
                        if (destArg is LambdaExpressionSyntax { Body: MemberAccessExpressionSyntax propAccess })
                        {
                            targetPropertyName = propAccess.Name.Identifier.ValueText;
                        }

                        if (!string.IsNullOrEmpty(targetPropertyName))
                        {
                            string finalizedExpression;
                            if (mapFromArg is LambdaExpressionSyntax sourceLambda)
                            {
                                var bodyStr = sourceLambda.Body.ToString();
                                var paramName = sourceLambda switch
                                {
                                    SimpleLambdaExpressionSyntax simple => simple.Parameter.Identifier.ValueText,
                                    ParenthesizedLambdaExpressionSyntax paren => paren.ParameterList.Parameters
                                        .FirstOrDefault()?.Identifier.ValueText,
                                    _ => null
                                };
                                finalizedExpression = !string.IsNullOrEmpty(paramName)
                                    ? bodyStr.Replace(paramName + ".", "data.")
                                    : bodyStr;
                            }
                            else
                            {
                                finalizedExpression = mapFromArg.ToString();
                            }

                            customRules[targetPropertyName!] = finalizedExpression;
                        }
                    }
                }
            }

            return customRules;
        }
    }
